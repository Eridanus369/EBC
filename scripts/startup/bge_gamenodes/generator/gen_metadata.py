def render(metadata):
    lines = [HEADER]
    lines.append('NATIVE_METADATA_GEN = {\n')
    for runtime_id in sorted(metadata):
        entry = metadata[runtime_id]
        lines.append('    {!r}: {{\n'.format(runtime_id))
        for side in ('inputs', 'outputs'):
            lines.append("        {!r}: (\n".format(side))
            for row in entry[side]:
                lines.append('            {!r},\n'.format(row,))
            lines.append('        ),\n')
        lines.append("        'config_keys': {!r},\n".format(entry['config_keys']))
        lines.append("        'ports_from_ir': {!r},\n".format(entry['ports_from_ir']))
        lines.append('    },\n')
    lines.append('}\n')
    return ''.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='fail if the generated table is out of date')
    parser.add_argument('--out', default=OUTPUT_PATH)
    args = parser.parse_args(argv)

    metadata = build_metadata()
    text = render(metadata)
    if args.check:
        try:
            current = open(args.out, encoding='utf-8').read()
        except OSError:
            current = ''
        if current != text:
            print('native_metadata_gen.py is stale, rerun gen_metadata.py')
            return 1
        print('native_metadata_gen.py is up to date ({} nodes)'.format(len(metadata)))
        return 0

    with open(args.out, 'w', encoding='utf-8') as handle:
        handle.write(text)
    print('wrote {} ({} nodes)'.format(args.out, len(metadata)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
